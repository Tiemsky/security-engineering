#!/usr/bin/env bash
# Build a read-only audit copy of a git repository's COMMITTED state, safe to hand to a read-only agent.
# Usage: scripts/audit-copy.sh --repo DIR --out NEW_DIR [--ref REV] [--dry-run]
#  - committed files only (via a private temporary index): the source repository is never written to
#  - uses the tracked-file list, NOT `git archive`, so `export-ignore` cannot silently drop files (pilot defect H1)
#  - drops secret-bearing files by name and by content shape, and symlinks; records every exclusion (path + reason, never a value)
#  - writes NEW_DIR/AUDIT-COPY.txt so the auditor can state what it could not see
# Exit: 0 ok · 1 error · 2 usage · 5 secret-bearing files were excluded (copy is still produced; tell the owner to rotate them)
set -euo pipefail

REPO="" OUT="" REF="HEAD" DRY=0
die() { echo "audit-copy: $*" >&2; exit "${2:-1}"; }
while [ $# -gt 0 ]; do
  case "$1" in
    --repo) REPO="${2:?}"; shift 2 ;;
    --out) OUT="${2:?}"; shift 2 ;;
    --ref) REF="${2:?}"; shift 2 ;;
    --dry-run) DRY=1; shift ;;
    -h|--help) sed -n 2,9p "$0"; exit 0 ;;
    *) die "unknown option: $1" 2 ;;
  esac
done
[ -n "$REPO" ] && [ -n "$OUT" ] || die "--repo and --out are required" 2
REPO="$(cd "$REPO" && pwd)"
git -C "$REPO" rev-parse --git-dir >/dev/null 2>&1 || die "not a git repository: $REPO"
COMMIT="$(git -C "$REPO" rev-parse --verify "$REF^{commit}")" || die "unknown ref: $REF"
mkdir -p "$OUT"; OUT="$(cd "$OUT" && pwd)"
case "$OUT/" in "$REPO"/*) die "--out must be outside the source repository" ;; esac
[ -z "$(ls -A "$OUT")" ] || die "--out must be empty"

BEFORE="$(git -C "$REPO" status --porcelain=v1 --ignored)"
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
export GIT_INDEX_FILE="$TMP/index"
git -C "$REPO" read-tree "$COMMIT"
TOTAL="$(git -C "$REPO" ls-files -z | tr -cd '\0' | wc -c)"

secret_name() {   # basename -> reason, or non-zero when fine
  case "$1" in
    .env.example|.env.sample|.env.dist|.env.template) return 1 ;;
    .env|.env.*) echo "env file" ;;
    *.pem|*.key|*.p12|*.pfx|*.jks|*.keystore|id_rsa|id_dsa|id_ecdsa|id_ed25519) echo "private key / keystore" ;;
    .npmrc|.netrc|.htpasswd|.pypirc) echo "credential file" ;;
    *.tfstate|*.tfstate.*|*.tfvars) echo "terraform state / variables" ;;
    credentials.json|service-account*.json|*serviceaccount*.json) echo "credential file" ;;
    *) return 1 ;;
  esac
}
SECRET_PATTERNS=(
  "private-key|-----BEGIN [A-Z ]*PRIVATE KEY-----"
  "aws-access-key|AKIA[0-9A-Z]{16}"
  "github-token|gh[pousr]_[A-Za-z0-9]{36,}"
  "slack-token|xox[baprs]-[A-Za-z0-9-]{10,}"
  "google-oauth-secret|GOCSPX-[A-Za-z0-9_-]{20,}"
  "brevo-smtp-key|xkeysib-[a-f0-9]{40,}"
  "stripe-live-key|sk_live_[A-Za-z0-9]{16,}"
  "anthropic-or-openai-key|sk-(ant|proj)-[A-Za-z0-9_-]{20,}"
)

EXCLUDED="$TMP/excluded.txt"; : > "$EXCLUDED"
if [ "$DRY" = 1 ]; then
  while IFS= read -r -d '' f; do
    if r="$(secret_name "$(basename "$f")")"; then printf '%s\t%s\n' "$f" "$r" >> "$EXCLUDED"; fi
  done < <(git -C "$REPO" ls-files -z)
  echo "dry-run: $TOTAL tracked file(s) at ${COMMIT:0:12}; $(wc -l < "$EXCLUDED") would be excluded by name (content scan needs a real run)"
  cat "$EXCLUDED"
  exit 0
fi

git -C "$REPO" checkout-index -a -f --prefix="$OUT/"
rm -rf "$OUT/.git"

# 1) symlinks (could point at host files outside the copy)
while IFS= read -r -d '' l; do printf '%s\tsymlink\n' "${l#"$OUT"/}" >> "$EXCLUDED"; rm -f "$l"; done < <(find "$OUT" -type l -print0)
# 2) secret-bearing file names
while IFS= read -r -d '' f; do
  if r="$(secret_name "$(basename "$f")")"; then printf '%s\t%s\n' "${f#"$OUT"/}" "$r" >> "$EXCLUDED"; rm -f "$f"; fi
done < <(find "$OUT" -type f -print0)
# 3) secret-shaped content in the remaining files (file path + type only; the value is never printed)
for entry in "${SECRET_PATTERNS[@]}"; do
  type="${entry%%|*}"; re="${entry#*|}"
  while IFS= read -r -d '' f; do
    printf '%s\tcontent shaped like %s\n' "${f#"$OUT"/}" "$type" >> "$EXCLUDED"; rm -f "$f"
  done < <(grep -rIlZE -e "$re" "$OUT" 2>/dev/null || true)
done

KEPT="$(find "$OUT" -type f | wc -l)"
{
  echo "AUDIT COPY — generated by scripts/audit-copy.sh (security-engineering)"
  echo "source: $(basename "$REPO")  ref: $REF  commit: $COMMIT"
  echo "created_utc: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "tracked_files: $TOTAL  kept: $KEPT  excluded: $(wc -l < "$EXCLUDED")"
  echo "method: committed state via temporary index; tracked-file list (export-ignore NOT honoured); symlinks removed"
  echo "excluded (path<TAB>reason). Anything listed here was NOT visible to the audit; do not report its absence as a finding:"
  sort "$EXCLUDED"
} > "$OUT/AUDIT-COPY.txt"

AFTER="$(env -u GIT_INDEX_FILE git -C "$REPO" status --porcelain=v1 --ignored)"
[ "$BEFORE" = "$AFTER" ] || die "source repository status changed during the copy (unexpected)"
echo "audit copy: $OUT ($KEPT file(s) kept, $(wc -l < "$EXCLUDED") excluded) — source repository unchanged"
if [ -s "$EXCLUDED" ] && grep -qE 'env file|private key|credential|content shaped|terraform' "$EXCLUDED"; then
  echo "WARNING: secret-bearing files are tracked in git (paths in $OUT/AUDIT-COPY.txt). Check whether they are real and rotate them." >&2
  exit 5
fi
