#!/usr/bin/env python3
"""Generate native agent files in adapters/<tool>/agents/ from agents/*.md + agents/manifest.json.
Usage: build-adapters.py [--check]   (--check exits 1 if generated files differ; used by tests/CI)"""
import json, sys, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
HEADER = "<!-- GENERATED by scripts/build-adapters.py from agents/ — do not edit by hand -->\n"

def split(text):
    _, fm, body = text.split("---\n", 2)
    meta = {}
    for line in fm.splitlines():
        k, _, v = line.partition(": ")
        v = v.strip(); meta[k.strip()] = json.loads(v) if v.startswith('"') else v
    return meta, body.lstrip("\n")

def q(s):  # YAML-safe double-quoted scalar
    return json.dumps(s, ensure_ascii=False)

def yaml_val(v, ind=0):
    pad = "  " * ind
    if isinstance(v, dict):
        return "".join(f"\n{pad}  {q(k)}:" + (yaml_val(x, ind + 1) if isinstance(x, dict) else " " + q(x)) for k, x in v.items())
    return " " + q(v)

def render(tool, name, meta, body, cfg):
    t = cfg[tool]
    skills_note = ("Skills to use: " + ", ".join(cfg["skills"]) + ".\n\n"
                   "Shared resources referenced as `core/`, `contracts/`, `policies/` resolve to `.security-engineering/shared/` in the project if present, "
                   "otherwise `~/.security-engineering/shared/`.")
    if tool == "claude":
        fm = [f"name: {name}", f"description: {q(meta['description'])}", "tools: " + ", ".join(t["tools"]), f"model: {t['model']}"]
        if "permissionMode" in t: fm.append(f"permissionMode: {t['permissionMode']}")
        fm.append("skills:"); fm += [f"  - {s}" for s in cfg["skills"]]
    elif tool == "opencode":
        fm = [f"description: {q(meta['description'])}", f"mode: {t['mode']}", "permission:"]
        for k, v in t["permission"].items():
            fm.append(f"  {k}:" + yaml_val(v, 1))
    else:
        fm = [f"name: {name}", f"description: {q(meta['description'])}", "tools:"] + [f"  - {x}" for x in t["tools"]]
        fm += ["model: inherit", f"commandExecutionPolicy: {t['commandExecutionPolicy']}", f"mainAgent: {str(t['mainAgent']).lower()}",
               f"subagent: {str(t['subagent']).lower()}", "skills:"] + [f"  - skills/{s}" for s in cfg["skills"]]
    return "---\n" + "\n".join(fm) + "\n---\n" + HEADER + "\n" + body.rstrip() + "\n\n" + skills_note.rstrip() + "\n"

def main():
    check = "--check" in sys.argv
    manifest = json.loads((ROOT / "agents/manifest.json").read_text())["agents"]
    dirs = {"claude": "claude-code", "opencode": "opencode", "antigravity": "antigravity"}
    diffs = 0
    for name, cfg in manifest.items():
        meta, body = split((ROOT / "agents" / cfg.get("source", f"{name}.md")).read_text())
        assert meta["name"] == name, f"{name}: spec name mismatch"
        for tool, d in dirs.items():
            out = ROOT / "adapters" / d / "agents" / f"{name}.md"
            text = render(tool, name, meta, body, cfg)
            if check:
                if not out.exists() or out.read_text() != text:
                    print(f"DRIFT: {out.relative_to(ROOT)}"); diffs += 1
            else:
                out.parent.mkdir(parents=True, exist_ok=True); out.write_text(text)
    sys.exit(1 if diffs else 0)
main()
